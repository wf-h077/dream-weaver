# 故事弧线感知系统
# ═══════════════════════════════════════════════════════

def get_story_phase(current_chapter: int, num_chapters: int) -> str:
    """
    根据当前章节号和总章节数，计算当前所处的叙事阶段，
    返回格式化的阶段描述字符串，供注入到各 agent 的 prompt 中。
    """
    if num_chapters <= 0:
        return ""

    progress = current_chapter / num_chapters  # 0.0 ~ 1.0
    remaining = num_chapters - current_chapter

    if progress <= 0.10:
        phase = "开局铺垫"
        instruction = (
            f"当前是全书的开头阶段（第{current_chapter}章/共{num_chapters}章）。\n"
            "创作要求：\n"
            "- 重点展开世界观，让读者迅速了解故事背景\n"
            "- 主角的日常生活与性格要鲜明呈现\n"
            "- 种下核心冲突的种子和未来的伏笔\n"
            "- 节奏平稳，但结尾要有一个'钩子'吸引读者继续阅读"
        )
    elif progress <= 0.40:
        phase = "发展攀升"
        instruction = (
            f"当前处于故事发展阶段（第{current_chapter}章/共{num_chapters}章）。\n"
            "创作要求：\n"
            "- 冲突逐步升级，敌人/困难越来越强\n"
            "- 主角不断成长，结交盟友或树敌\n"
            "- 推进主线的同时适当展开支线\n"
            "- 制造悬念和期待感，为高潮积蓄能量"
        )
    elif progress <= 0.75:
        phase = "高潮爆发"
        instruction = (
            f"当前是故事的高潮阶段（第{current_chapter}章/共{num_chapters}章）。\n"
            "创作要求：\n"
            "- 核心冲突全面爆发，战斗和对决密集\n"
            "- 开始回收之前埋下的伏笔\n"
            "- 重要的反转和揭秘应在此阶段出现\n"
            "- 人物关系发生重大变化，情感冲击力要强"
        )
    elif progress <= 0.90:
        phase = "最终决战"
        instruction = (
            f"当前是故事最终决战阶段（第{current_chapter}章/共{num_chapters}章，"
            f"距离结局仅剩{remaining}章）。\n"
            "创作要求：\n"
            "- 主角面对终极对手/终极困境\n"
            "- 所有伏笔和悬念必须在此阶段或下一阶段解决\n"
            "- 不要再开新坑！不要引入新角色或新势力\n"
            "- 节奏紧凑，一气呵成推向最终高潮\n"
            "- 主角的核心抉择必须在此阶段做出"
        )
    else:
        phase = "大结局"
        instruction = (
            f"当前是全书的最终阶段！（第{current_chapter}章/共{num_chapters}章，"
            f"仅剩{remaining}章就要完结）\n"
            "创作要求：\n"
            "- 所有未解决的冲突和悬念必须在这几章内全部收束\n"
            "- 给出主角和重要角色的最终命运交代\n"
            "- 呼应开头的伏笔，形成完整的故事闭环\n"
            "- 最后一章需要有明确的'完结'感：战后余韵、角色归宿、人生感悟\n"
            "- 不允许留下未解之谜或开放式结局（除非用户特别要求）"
        )
        if current_chapter == num_chapters:
            instruction += (
                "\n\n这是全书最后一章！请以完美的大结局收束全部故事线！\n"
                "必须让读者感受到'这本书看完了'的满足感。"
            )

    return f"【故事阶段：{phase}】\n{instruction}"


