def score_pattern(pattern: dict, text: str) -> int:
    score = 0
    for keyword in pattern.get("keywords", []):
        if keyword and keyword in text:
            score += 2
    return score


def select_chapter_pattern(state: NovelState) -> dict:
    chapter_num = state["current_chapter"]
    text = "\n".join([
        state.get("novel_genre", ""),
        state.get("novel_style", ""),
        state.get("chapter_outline", ""),
        state.get("chapter_controls_text", ""),
        get_story_phase(chapter_num, state.get("num_chapters", 100)),
    ])

    best = max(CHAPTER_PATTERNS, key=lambda item: score_pattern(item, text))
    if score_pattern(best, text) <= 0:
        # 开局阶段优先给可读性更强的压迫/线索模板，其他阶段用过渡蓄势兜底。
        if chapter_num <= max(3, int(state.get("num_chapters", 100) * 0.08)):
            best = CHAPTER_PATTERNS[0]
        else:
            best = CHAPTER_PATTERNS[-1]

    report_progress(f"已匹配章节样板：{best['name']}", "planning")
    print(f"\n[章节样板] 第{chapter_num}章匹配：{best['name']}")
    return {
        "chapter_pattern_card": best["card"],
    }
